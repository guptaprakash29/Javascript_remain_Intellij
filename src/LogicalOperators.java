public class LogicalOperators {
    public static void main(String[] args) {
        boolean a = true;
        boolean b = false;

        // Logical AND
        System.out.println(a && b);   // false

        // Logical OR
        System.out.println(a || b);   // true

        // Logical NOT
        System.out.println(!a);       // false
    }
}
