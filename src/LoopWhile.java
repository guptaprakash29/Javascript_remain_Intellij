public class LoopWhile {
    static void main(String[] args) {

        {
            int i = 5;
            while (i >= 1) {
                System.out.print(i + " ");
                i--;
            }
        }
        System.out.println();
        {
            int i = 10;
            while (i <= 20) {
                System.out.print(i + " ");
                i++;    //  i=i+1; i+=1;

            }
        }
    }
}
