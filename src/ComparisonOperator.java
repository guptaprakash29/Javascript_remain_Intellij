public class ComparisonOperator {

    public static void main(String[] args) {

        int y = 10;
        int z = 20;

        // Equal to
        System.out.println(y == z);  // false

        // Inequality (Not equal to)
        System.out.println(y != z);  // true

        // Greater than
        System.out.println(y > z);   // false

        // Less than
        System.out.println(y < z);   // true

        // Greater than or equal to
        System.out.println(y >= z);  // false

        // Less than or equal to
        System.out.println(y <= z);  // true
    }
}

