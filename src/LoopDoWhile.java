public class LoopDoWhile {
    static void main(String[] args) {
        {
            int i = 5;
            do {
                System.out.print(i + " ");
                i--;
            } while (i >= 1);
        }
        System.out.println();
        {
            int i = 10;
            do {
                System.out.print(i + " ");
                i++;
            } while (i <= 20);
        }

    }
}
