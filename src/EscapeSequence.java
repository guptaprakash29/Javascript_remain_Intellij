public static void main(String[] args) {
    System.out.println("Hello,\nWorld!");             // New line
    System.out.println("She said, \"Java is fun!\""); // Double quotes
    System.out.println("Path: C:\\Program Files\\");  // Backslash
    System.out.println("Tab\tSeparated");             // Tab
    System.out.println("Carriage\rReturn");           // Carriage return (may overwrite part of line)
    System.out.println("Back\bspace");                // Backspace (removes previous character visually)
    System.out.println("Single quote: \'");           // Single quote
    char mno = '\'';
    System.out.println(mno);
    System.out.println("Unicode Omega: \u03A9");      // Unicode character (Ω)
}